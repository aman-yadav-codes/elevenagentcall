async function seed() {
  console.log("Connecting to MongoDB Atlas...");
  const client = new MongoClient(uri);

  try {
    await client.connect();
    console.log("Connected to MongoDB Atlas!");

    const db = client.db("supermarket_db");

    // Clean drop
    await db.collection("sections").drop().catch(() => {});
    await db.collection("products").drop().catch(() => {});
    await db.collection("stock_alerts").drop().catch(() => {});
    await db.collection("customers").drop().catch(() => {});
    await db.collection("operations_logs").drop().catch(() => {});

    // Inserts
    const secResult = await db.collection("sections").insertMany(sections);
    console.log(`✓ Inserted ${secResult.insertedCount} supermarket sections across Aisles 1-8.`);

    const prodResult = await db.collection("products").insertMany(products);
    console.log(`✓ Inserted ${prodResult.insertedCount} supermarket products with variants, SKUs, and stock levels.`);

    const custResult = await db.collection("customers").insertMany(customers);
    console.log(`✓ Inserted ${custResult.insertedCount} regular loyalty supermarket customers.`);

    const alertResult = await db.collection("stock_alerts").insertMany(stockAlerts);
    console.log(`✓ Inserted ${alertResult.insertedCount} manager stock alerts.`);

    // Indexes
    await db.collection("products").createIndex({ name: "text", category: "text", sku: "text" });
    await db.collection("customers").createIndex({ name: "text", customerId: 1, phone: 1 });
    await db.collection("sections").createIndex({ sectionId: 1 }, { unique: true });

    console.log("✓ Created indexes for real-time AI voice querying.");
    console.log("Supermarket database successfully seeded!");
  } finally {
    await client.close();
  }
}

